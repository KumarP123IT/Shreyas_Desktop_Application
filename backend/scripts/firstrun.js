/**
 * First-Run Setup Script
 * ─────────────────────
 * Runs automatically on first install (before the main server starts).
 * • Generates cryptographically-random JWT_SECRET and ENCRYPTION_KEY
 * • Writes backend/.env if it doesn't exist
 * • Creates the storage directory structure
 * • Runs Prisma migrations  (SQLite — no MySQL/server needed)
 * • Seeds the database (default admin user + MSL global defaults)
 * • Writes a marker file so this script is skipped on subsequent starts
 *
 * IMPORTANT: Uses node_modules/.bin/prisma directly — never relies on
 * npx or a globally installed Prisma. Safe inside a Windows Service.
 */

'use strict';

const { execFileSync } = require('child_process');
const crypto = require('crypto');
const fs     = require('fs');
const path   = require('path');

const ROOT     = path.resolve(__dirname, '..');   // = backend/
const ENV_FILE = path.join(ROOT, '.env');
const MARKER   = path.join(ROOT, 'storage', '.firstrun_done');

// ── Already initialised ───────────────────────────────────────────────────────
if (fs.existsSync(MARKER)) {
  console.log('[firstrun] Already initialised, skipping.');
  process.exit(0);
}

console.log('[firstrun] ─── Smart MSL Monitor — First-Run Setup ───');

// ── 1. Generate secrets ───────────────────────────────────────────────────────
const jwtSecret     = crypto.randomBytes(48).toString('hex');  // 96 chars
const encryptionKey = crypto.randomBytes(32).toString('hex');  // 64 chars

// ── 2. Resolve DB path and write .env ────────────────────────────────────────
// MSL_DATA_DIR is set by the NSSM service to %APPDATA%\SmartMSLMonitor\data
const dataDir = process.env.MSL_DATA_DIR
  ? path.resolve(process.env.MSL_DATA_DIR)
  : path.join(ROOT, 'storage', 'data');

fs.mkdirSync(dataDir, { recursive: true });

const dbPath = path.join(dataDir, 'msl.db');
// Prisma requires forward slashes in file: URLs on all platforms
const dbUrl  = `file:${dbPath.replace(/\\/g, '/')}`;

const storageRoot = path.join(ROOT, 'storage').replace(/\\/g, '/');
const logDir      = path.join(ROOT, 'logs').replace(/\\/g, '/');

const envContent = `# Auto-generated by first-run setup — do not edit manually
DATABASE_URL="${dbUrl}"

JWT_SECRET="${jwtSecret}"
JWT_EXPIRES_IN="8h"
JWT_REMEMBER_EXPIRES_IN="30d"

ENCRYPTION_KEY="${encryptionKey}"

PORT=4000
NODE_ENV=production
FRONTEND_DIST=./frontend/dist

STORAGE_ROOT=${storageRoot}
LOG_LEVEL=info
LOG_DIR=${logDir}
SCHEDULER_INTERVAL_SEC=30
`;

if (!fs.existsSync(ENV_FILE)) {
  fs.writeFileSync(ENV_FILE, envContent, 'utf8');
  console.log('[firstrun] Created .env with generated secrets.');
} else {
  console.log('[firstrun] .env already exists – skipping write.');
}

// ── 3. Create directory structure ─────────────────────────────────────────────
const dirs = [
  dataDir,
  path.join(ROOT, 'storage', 'uploads'),
  path.join(ROOT, 'storage', 'uploads', '_temp'),
  path.join(ROOT, 'storage', 'backups'),
  path.join(ROOT, 'logs'),
];
for (const d of dirs) fs.mkdirSync(d, { recursive: true });
console.log('[firstrun] Storage directories created.');

// ── 4. Locate node executable and Prisma CLI ──────────────────────────────────
// process.execPath = the node.exe bundled by the installer
const nodeExe = process.execPath;

// Prisma CLI entry point — always present after npm install
const prismaCli = path.join(ROOT, 'node_modules', 'prisma', 'build', 'index.js');
if (!fs.existsSync(prismaCli)) {
  console.error('[firstrun] Prisma CLI not found at:', prismaCli);
  console.error('[firstrun] Make sure node_modules is present in the install directory.');
  process.exit(1);
}

// Shared env for child processes
const childEnv = {
  ...process.env,
  DATABASE_URL: dbUrl,
  // Make sure node_modules/.bin is on PATH for any sub-processes Prisma spawns
  PATH: `${path.join(ROOT, 'node_modules', '.bin')}${path.delimiter}${process.env.PATH || ''}`,
};

// ── 5. Run Prisma migrations ───────────────────────────────────────────────────
console.log('[firstrun] Running database migrations…');
try {
  execFileSync(nodeExe, [prismaCli, 'migrate', 'deploy'], {
    cwd: ROOT,
    stdio: 'inherit',
    env: childEnv,
  });
  console.log('[firstrun] Migrations applied.');
} catch (err) {
  console.error('[firstrun] Migration failed:', err.message);
  // Try the fallback: run prisma via node_modules/.bin/prisma (Windows .cmd)
  try {
    console.log('[firstrun] Trying fallback migration path…');
    const prismaBin = path.join(ROOT, 'node_modules', '.bin',
      process.platform === 'win32' ? 'prisma.cmd' : 'prisma');
    execFileSync(prismaBin, ['migrate', 'deploy'], {
      cwd: ROOT,
      stdio: 'inherit',
      env: childEnv,
      shell: process.platform === 'win32',
    });
    console.log('[firstrun] Migrations applied (fallback).');
  } catch (err2) {
    console.error('[firstrun] Migration failed (both paths):', err2.message);
    process.exit(1);
  }
}

// ── 6. Seed the database ──────────────────────────────────────────────────────
console.log('[firstrun] Seeding database…');
try {
  execFileSync(nodeExe, [path.join(ROOT, 'prisma', 'seed.js')], {
    cwd: ROOT,
    stdio: 'inherit',
    env: childEnv,
  });
  console.log('[firstrun] Seed complete.');
} catch (err) {
  console.warn('[firstrun] Seed warning (non-fatal):', err.message);
}

// ── 6b. Verify an admin account exists — without it nobody can log in ─────────
console.log('[firstrun] Verifying admin account…');
try {
  execFileSync(nodeExe, ['-e', `
    const { PrismaClient } = require('@prisma/client');
    const p = new PrismaClient();
    p.user.findUnique({ where: { username: 'admin' } })
      .then(u => process.exit(u ? 0 : 2))
      .catch(() => process.exit(3))
      .finally(() => p.$disconnect());
  `], { cwd: ROOT, stdio: 'pipe', env: childEnv });
} catch (err) {
  console.error('[firstrun] FATAL: no admin user found after seeding.');
  console.error('[firstrun] Re-run setup or seed manually: node prisma/seed.js');
  process.exit(1);
}
console.log('[firstrun] Admin account verified.');

// ── 7. Write the marker ───────────────────────────────────────────────────────
fs.mkdirSync(path.dirname(MARKER), { recursive: true });
fs.writeFileSync(MARKER, new Date().toISOString(), 'utf8');
console.log('[firstrun] Setup complete. ✔');
