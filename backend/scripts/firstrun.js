/**
 * First-Run Setup Script
 * ─────────────────────
 * Runs automatically on first install (before the main server starts).
 * • Generates cryptographically-random JWT_SECRET and ENCRYPTION_KEY
 * • Writes backend/.env from the template if it doesn't exist
 * • Creates the storage directory structure
 * • Runs Prisma migrations (creates the SQLite database)
 * • Seeds the database (default admin user + MSL global defaults)
 * • Writes a marker file so this script is skipped on subsequent starts
 */

'use strict';

const { execSync } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT   = path.resolve(__dirname, '..');   // = backend/
const ENV_FILE = path.join(ROOT, '.env');
const MARKER   = path.join(ROOT, 'storage', '.firstrun_done');

// Already initialised — nothing to do
if (fs.existsSync(MARKER)) {
  console.log('[firstrun] Already initialised, skipping.');
  process.exit(0);
}

console.log('[firstrun] ─── Smart MSL Monitor — First-Run Setup ───');

// ── 1. Generate secrets ───────────────────────────────────────────────────────
const jwtSecret = crypto.randomBytes(48).toString('hex');       // 96 chars
const encryptionKey = crypto.randomBytes(32).toString('hex');   // 64 chars

// ── 2. Resolve the DB path and write .env ─────────────────────────────────────
// Prefer ProgramData for multi-user setups on Windows, fall back to storage/
const dataDir = process.env.MSL_DATA_DIR
  ? path.resolve(process.env.MSL_DATA_DIR)
  : path.join(ROOT, 'storage', 'data');

fs.mkdirSync(dataDir, { recursive: true });

const dbPath = path.join(dataDir, 'msl.db');
// On Windows, Prisma file: URLs need forward slashes
const dbUrl = `file:${dbPath.replace(/\\/g, '/')}`;

const storageRoot = path.join(ROOT, 'storage').replace(/\\/g, '/');
const logDir = path.join(ROOT, 'logs').replace(/\\/g, '/');

const envContent = `# Auto-generated by first-run setup — do not edit manually
DATABASE_URL="${dbUrl}"

JWT_SECRET="${jwtSecret}"
JWT_EXPIRES_IN="8h"
JWT_REMEMBER_EXPIRES_IN="30d"

ENCRYPTION_KEY="${encryptionKey}"

PORT=4000
NODE_ENV=production
FRONTEND_DIST=../frontend/dist

STORAGE_ROOT=${storageRoot}
LOG_LEVEL=info
LOG_DIR=${logDir}
SCHEDULER_INTERVAL_SEC=30
`;

// Only write if .env doesn't already exist (protect user edits on update)
if (!fs.existsSync(ENV_FILE)) {
  fs.writeFileSync(ENV_FILE, envContent, 'utf8');
  console.log('[firstrun] Created .env with generated secrets.');
} else {
  console.log('[firstrun] .env already exists – skipping write.');
}

// ── 3. Create directory structure ─────────────────────────────────────────────
const dirs = [
  dataDir,
  path.join(ROOT, 'storage', 'uploads'),
  path.join(ROOT, 'storage', 'uploads', '_temp'),
  path.join(ROOT, 'storage', 'backups'),
  path.join(ROOT, 'logs'),
];
for (const d of dirs) {
  fs.mkdirSync(d, { recursive: true });
}
console.log('[firstrun] Storage directories created.');

// ── 4. Run Prisma migrations ──────────────────────────────────────────────────
console.log('[firstrun] Running database migrations…');
try {
  execSync('npx prisma migrate deploy', {
    cwd: ROOT,
    stdio: 'inherit',
    env: { ...process.env, DATABASE_URL: dbUrl },
  });
  console.log('[firstrun] Migrations applied.');
} catch (err) {
  console.error('[firstrun] Migration failed:', err.message);
  process.exit(1);
}

// ── 5. Seed the database ──────────────────────────────────────────────────────
console.log('[firstrun] Seeding database…');
try {
  execSync('node prisma/seed.js', {
    cwd: ROOT,
    stdio: 'inherit',
    env: { ...process.env, DATABASE_URL: dbUrl },
  });
  console.log('[firstrun] Seed complete.');
} catch (err) {
  // Non-fatal if seed fails (data might already exist)
  console.warn('[firstrun] Seed warning:', err.message);
}

// ── 6. Write the marker so we skip this next time ────────────────────────────
fs.mkdirSync(path.dirname(MARKER), { recursive: true });
fs.writeFileSync(MARKER, new Date().toISOString(), 'utf8');
console.log('[firstrun] Setup complete. ✔');
